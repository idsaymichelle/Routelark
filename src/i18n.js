// Plural forms: en - [one, other], ru - [one, few, many]
export const PL = {
  finding: { en: ['finding', 'findings'], ru: ['находка', 'находки', 'находок'] },
  file: { en: ['file scanned', 'files scanned'], ru: ['файл прочитан', 'файла прочитано', 'файлов прочитано'] }
};

export function t(s, vars) {
  let r = s;
  if (lang === 'ru' && typeof s === 'string') {
    if (Object.prototype.hasOwnProperty.call(RU, s)) r = RU[s];
    else for (const [re, to] of RU_PATTERNS) { const m = re.exec(s); if (m) { r = typeof to === 'function' ? to(m) : s.replace(re, to); break; } }
  }
  if (vars && typeof vars === 'object' && typeof r === 'string') r = r.replace(/\{(\w+)\}/g, (a, k) => (k in vars ? vars[k] : a));
  return r;
}

function formIndex(n) {
  try { const c = new Intl.PluralRules(lang).select(n); return lang === 'ru' ? (c === 'one' ? 0 : c === 'few' ? 1 : 2) : (c === 'one' ? 0 : 1); }
  catch (e) {
    if (lang !== 'ru') return n === 1 ? 0 : 1;
    const a = n % 10, b = n % 100; return a === 1 && b !== 11 ? 0 : a >= 2 && a <= 4 && (b < 12 || b > 14) ? 1 : 2;
  }
}
export function plural(n, forms) {
  const f = forms[lang] || forms.en;
  return n + ' ' + (f[formIndex(n)] || f[f.length - 1]);
}

